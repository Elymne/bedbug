/// Largeurs de rupture utilisées pour adapter la mise en page à la taille
/// de l'écran.
class AppBreakpoints {
  /// Largeur maximale d'un écran considéré comme mobile.
  static const double mobile = 600.0;

  /// Largeur minimale d'un écran considéré comme tablette.
  static const double tablet = 900.0;

  /// Largeur de la sidebar en mode étendu sur desktop.
  static const double desktopSidebar = 240.0;

  /// Largeur minimale d'un écran considéré comme desktop.
  static const double desktop = 1100.0;

  /// Largeur maximale de la zone de contenu principal.
  static const double maxDisplay = 1400.0;
}
